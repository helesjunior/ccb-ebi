// Bootstrap do codegen: registra o loader que faz openapi-typescript
// resolver o specifier 'typescript' para o TypeScript 5 (dep "typescript5")
// e então chama a API programática do openapi-typescript.
//
// Uso (equivalente à CLI):
//   node tools/gen-api.mjs <spec.yaml> -o <saida.d.ts>
import { register } from 'node:module';
import { readFile, writeFile } from 'node:fs/promises';

register('./ts5-loader.mjs', import.meta.url);

// Lê os argumentos no mesmo formato da CLI do openapi-typescript: <input> [-o <output>].
let input;
let output;
const args = process.argv.slice(2);
for (let i = 0; i < args.length; i++) {
  if (args[i] === '-o' || args[i] === '--output') {
    output = args[++i];
  } else if (!input) {
    input = args[i];
  }
}
if (!input) {
  console.error('uso: node tools/gen-api.mjs <openapi.yaml> [-o <saida.d.ts>]');
  process.exit(1);
}

const { default: openapiTS, astToString } = await import('openapi-typescript');

// Cabeçalho idêntico ao que a CLI do openapi-typescript escreve, para o
// arquivo regenerado bater byte-a-byte com o versionado.
const HEADER =
  '/**\n' +
  ' * This file was auto-generated by openapi-typescript.\n' +
  ' * Do not make direct changes to the file.\n' +
  ' */\n\n';

const source = await readFile(input, 'utf8');
const ast = await openapiTS(source);
const contents = HEADER + astToString(ast);

if (output) {
  await writeFile(output, contents);
  console.log(`gerado ${output}`);
} else {
  process.stdout.write(contents);
}